// Package textwidth считает визуальную ширину строк и обрезает их так, как
// это делают клиенты Telegram — по ШИРИНЕ, а не по рунам.
//
// Общий пакет для бота и отладочной утилиты cmd/btnprobe: обрезка в тестах
// должна быть байт-в-байт той же, что в проде, иначе подбор лимитов врёт.
package textwidth

import (
	"strings"
	"unicode"

	"github.com/rivo/uniseg"
)

// MaxLabelWidth — бюджет визуальной ширины подписи inline-кнопки в ряду из
// ОДНОЙ кнопки.
//
// Это НЕ руны и НЕ символы: Telegram-клиенты обрезают подпись по визуальной
// ширине, и лимит зависит от шрифта конкретного клиента. Замерено вживую
// через cmd/btnprobe на Telegram Desktop (октябрь 2026): 33 целиком влезает,
// 34 уже режется → 33 с нулевым запасом, то есть граница клиента.
//
// На другом клиенте (iOS/Android/Web — не замерялись) лимит может быть
// строже, тогда сработает клиентская обрезка — это осознанный риск, см.
// док-K LabelBudget.
const MaxLabelWidth = 33

// LabelBudget возвращает бюджет ширины подписи для ряда из per кнопок.
//
// Лимит падает с ростом числа кнопок: ширина ряда делится между кнопками,
// поэтому в ряду из двух по 33 не влезет ни одна. Значения сняты вживую
// через cmd/btnprobe (режим edge), не выведены из теории; клиент — Telegram
// Desktop, замер October 2026, чистая кириллица:
//
//	1 кнопка → 33   замер: 33 («…ьэюя») целое, 34 режется
//	2 кнопки  → 17   замер: 17 («…клмноп») целое, 18+ режется
//	3 кнопки  → 10   замер: 10 (🔥×4+«аб»), 11+ режется
//	4 кнопки  → 7    замер: 7 (🔥×3+«а»), 8 режется
//	5 кнопок  → 5    замер: 5 (🔥×2+«а»), 6+ режется
//
// Запас 0 везде — сознательно: бюджет равен измеренной границе клиента,
// чтобы подпись была максимально читаемой. Обрезка наша срабатывает на
// единицу раньше клиентской, и только на этих значениях. На более строгом
// шрифте (iOS, Android, Web ещё не замерялись) может сработать клиентская
// обрезка.
//
// ВАЖНО: бюджет имеет смысл только вместе с числом кнопок в ряду, где
// подпись лежит. Вызывающий код обязан передавать len(ряда) — иначе обрезка
// считается для одного числа, а кнопка стоит в другом ряду.
//
// При 0 и меньше считаем одну кнопку: бюджет единственный, что разумнее
// пустого.
func LabelBudget(per int) int {
	switch {
	case per <= 1:
		return MaxLabelWidth
	case per == 2:
		return 17
	case per == 3:
		return 10
	case per == 4:
		return 7
	default:
		return 5
	}
}

// Truncate укорачивает s до max единиц визуальной ширины, ставя «…».
// Инвариант: Width(результат) ≤ max при max ≥ 2. При max < 2 возвращает
// «…» усечённо — строку шириной 1, потому что иначе инвариант нарушен
// (см. док-Truncate про многоточие).
//
// Срез идёт по ГРАФЕМАМ, то есть по визуальным символам: эмодзи-кластер не
// режется пополам. Семья «👨‍👩‍👧‍👦» — 7 рун, но одна графема шириной 2;
// рунная обрезка давала бы мусорный half-эмодзи, который Telegram рисует
// битым.
//
// Полуслово в конце СОХРАНЯЕТСЯ: «Беговой чат жителей Пер…» отличает чат в
// Перово от такого же в Коньково, а откат до границы слова («жителей…»)
// сделал бы обе кнопки одинаковыми.
func Truncate(s string, max int) string {
	if Width(s) <= max {
		return s
	}
	if max < 2 {
		return "…"
	}
	// Многоточие занимает одну единицу, поэтому режем на max-1.
	return Exact(s, max-1) + "…"
}

// Exact обрезает s до max единиц ширины БЕЗ многоточия, по графемам.
// Используется внутри Truncate и утилитой btnprobe, когда ширина задаётся
// точно и решение принимает клиент, а не наш код.
func Exact(s string, max int) string {
	if max < 1 {
		return ""
	}
	var sb strings.Builder
	w := 0
	gr := uniseg.NewGraphemes(s)
	for gr.Next() {
		g := gr.Str()
		gw := graphemeWidth(g)
		if w+gw > max {
			break
		}
		sb.WriteString(g)
		w += gw
	}
	// Хвостовой пробел убираем: «Беговой чат жителей …» нечитаем, пробел
	// перед многоточием виден как дырка. Срез по пробелу НЕ откатываемся к
	// границе слова — полуслово остаётся (см. док-Truncate). Убираем все
	// Unicode-пробелы, не только ASCII: NBSP и таб так же видны как дырка.
	return strings.TrimRightFunc(sb.String(), unicode.IsSpace)
}

// Width — визуальная ширина строки в условных единицах: кириллица/латиница/
// цифры 1, эмодзи и широкие символы 2, невидимые связки (ZWJ, variation
// selector, тон кожи внутри кластера) 0.
//
// Приближение реальной ширины в шрифте Telegram: точное совпадение с каждым
// клиентом (iOS/Android/Desktop/Web) невозможно, важен порядок величины,
// чтобы обрезка срабатывала ДО клиентской.
func Width(s string) int {
	w := 0
	gr := uniseg.NewGraphemes(s)
	for gr.Next() {
		w += graphemeWidth(gr.Str())
	}
	return w
}

// graphemeWidth — ширина одной графемы в наших единицах.
//
// uniseg считает по Unicode East Asian Width, беря основу графемы: у клавиши
// «1️⃣» основа — ASCII-цифра, и он даёт 1. Клиенты Telegram рисуют клавишу
// КВАДРАТНОЙ, как обычное эмодзи, то есть шириной 2. Замерено вживую
// (btnprobe -mode kseq): при ширине 1 клавиша 8-я резалась, при 2 — ровно
// там, где клиент. Поэтому кластер с keycap-маркером считаем за 2.
//
// Остальные графемы отдаём на откуп uniseg: там он корректен (эмодзи 2,
// кластеры 2, буквы 1).
func graphemeWidth(g string) int {
	// U+20E3 COMBINING ENCLOSING KEYCAP — маркер цифровой клавиши «1️⃣».
	if strings.ContainsRune(g, '\u20e3') {
		return 2
	}
	return uniseg.StringWidth(g)
}
